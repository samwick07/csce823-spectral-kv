#!/usr/bin/env bash
# =============================================================================
# push_results_github.sh — Push evaluation results to GitHub.
#
# The .gitignore excludes results/, checkpoints/, and logs/ to keep the
# repo lean during development. This script force-adds the eval result
# JSONs (not checkpoints or logs) so they are version-controlled.
#
# Usage:
#   bash scripts/push_results_github.sh
#
# Requires git credentials (set via origin URL or GH_TOKEN env var).
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
cd "$PROJECT_ROOT"

echo "=== Pushing eval results to GitHub ==="

# Force-add results JSONs (overcomes .gitignore exclusion)
git add -f results/raw/*/seed_*/all_results.json 2>/dev/null || true
git add -f results/raw/*/seed_*/*.json 2>/dev/null || true
git add -f results/aggregated/*.csv 2>/dev/null || true
git add -f results/aggregated/*.json 2>/dev/null || true
git add -f results/statistical_analysis.json 2>/dev/null || true
git add -f results/orchestrator_state.json 2>/dev/null || true

# Also add the patched source files
git add src/eval/proof_pile.py src/run_experiment.py requirements.txt 2>/dev/null || true

# Check if there is anything to commit
if git diff --cached --quiet; then
    echo "Nothing to commit. Results may already be up to date."
    exit 0
fi

TIMESTAMP=$(date -u "+%Y-%m-%d %H:%M:%S UTC")
git commit -m "eval: benchmark results + eval fixes (zstandard, W&B import, GitHub push)

- Fix Proof-pile loading: add zstandard dep, trust_remote_code for proof-pile-2,
  retry logic with backoff for HF Hub 429 rate limits
- Fix W&B init: fallback to absolute import when run as script (not -m)
- Add GitHub results push script
- Results timestamp: ${TIMESTAMP}

Generated by orchestrator eval phase."

git push origin HEAD 2>&1

echo "=== GitHub push complete ==="
